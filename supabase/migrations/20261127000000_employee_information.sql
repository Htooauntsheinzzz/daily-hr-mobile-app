-- Employee information: departments, positions, generated employee IDs,
-- and tighter rules for who can change pay, status and login accounts.
-- Run once in the SQL Editor after the earlier migrations.

-- ---------------------------------------------------------------------------
-- Departments and positions
-- ---------------------------------------------------------------------------

create table public.departments (
  name text primary key check (length(trim(name)) > 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.positions (
  name text primary key check (length(trim(name)) > 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Start with the names the app already uses and any already on employees.
insert into public.departments (name)
select name from (
  values ('People Operations'), ('Product Design'), ('Business Operations')
) as v(name)
union
select distinct department from public.employees
on conflict do nothing;

insert into public.positions (name)
select name from (
  values ('People Coordinator'), ('Design Associate'), ('Team Lead'),
         ('HR Administrator')
) as v(name)
union
select distinct position from public.employees
on conflict do nothing;

-- Every employee must use a department and position from these lists.
-- Renaming a department or position updates the employees that use it.
alter table public.employees
  add constraint employees_department_fkey foreign key (department)
    references public.departments (name) on update cascade,
  add constraint employees_position_fkey foreign key (position)
    references public.positions (name) on update cascade;

alter table public.departments enable row level security;
alter table public.positions enable row level security;

create policy "Signed-in users see departments" on public.departments
  for select to authenticated using (true);
create policy "HR adds departments" on public.departments
  for insert to authenticated with check ((select public.is_hr()));
create policy "HR edits departments" on public.departments
  for update to authenticated using ((select public.is_hr()));
create policy "HR deletes unused departments" on public.departments
  for delete to authenticated using ((select public.is_hr()));

create policy "Signed-in users see positions" on public.positions
  for select to authenticated using (true);
create policy "HR adds positions" on public.positions
  for insert to authenticated with check ((select public.is_hr()));
create policy "HR edits positions" on public.positions
  for update to authenticated using ((select public.is_hr()));
create policy "HR deletes unused positions" on public.positions
  for delete to authenticated using ((select public.is_hr()));

grant select, insert, update, delete on public.departments, public.positions
  to authenticated;
grant all on public.departments, public.positions to service_role;

-- ---------------------------------------------------------------------------
-- Employee IDs: DH-004, DH-005, ... generated by the database
-- ---------------------------------------------------------------------------

create sequence public.employee_number_seq;
select setval(
  'public.employee_number_seq',
  greatest(coalesce(
    (select max(substring(id from 4)::bigint) from public.employees), 0), 1)
);
alter table public.employees
  alter column id set default
    'DH-' || lpad(nextval('public.employee_number_seq')::text, 3, '0');
grant usage on sequence public.employee_number_seq to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- Rules for adding and editing employees
-- ---------------------------------------------------------------------------

-- New employees can only use active departments and positions.
create function public.check_employee_catalog()
returns trigger language plpgsql set search_path = '' as $$
begin
  if public.is_trusted_role() then
    return new;
  end if;
  if (tg_op = 'INSERT' or new.department is distinct from old.department)
     and not exists (select 1 from public.departments
                     where name = new.department and active) then
    raise exception 'Choose an active department.';
  end if;
  if (tg_op = 'INSERT' or new.position is distinct from old.position)
     and not exists (select 1 from public.positions
                     where name = new.position and active) then
    raise exception 'Choose an active position.';
  end if;
  return new;
end;
$$;

-- HR adds employees without a login. Logins are created by the
-- create-employee-login Edge Function, or linked by matching email.
create function public.guard_employee_insert()
returns trigger language plpgsql set search_path = '' as $$
begin
  if public.is_trusted_role() then
    return new;
  end if;
  if new.user_id is not null then
    raise exception 'Use Create login to give an employee a login.';
  end if;
  return new;
end;
$$;

-- Who can change what on an employee record:
--   * Nobody in the app can change the employee ID or the linked login.
--   * The work email can't change once the employee has a login.
--   * HR can edit records, pay and status, but not their own pay or status.
--   * Employees can only change their own mobile number and personal email.
create or replace function public.guard_employee_update()
returns trigger language plpgsql set search_path = '' as $$
begin
  if public.is_trusted_role() then
    return new;
  end if;
  if new.id is distinct from old.id
     or new.user_id is distinct from old.user_id
     or new.created_at is distinct from old.created_at then
    raise exception 'Employee IDs and logins can only be changed by an administrator.';
  end if;
  if old.user_id is not null and new.email is distinct from old.email then
    raise exception 'This employee already has a login, so the work email can''t be changed.';
  end if;
  if public.is_hr() then
    if old.id = public.current_employee_id() and (
         new.base_salary is distinct from old.base_salary
         or new.overtime_rate is distinct from old.overtime_rate
         or new.insurance is distinct from old.insurance
         or new.advance is distinct from old.advance
         or new.active is distinct from old.active) then
      raise exception 'HR administrators can''t change their own pay or status.';
    end if;
    return new;
  end if;
  if (to_jsonb(new) - array['mobile', 'personal_email', 'updated_at'])
     is distinct from (to_jsonb(old) - array['mobile', 'personal_email', 'updated_at']) then
    raise exception 'Only HR can change this employee information.';
  end if;
  return new;
end;
$$;

-- Triggers run in name order: the insert guard runs before employees_link
-- fills in user_id for an existing login with the same email.
create trigger employees_catalog before insert or update on public.employees
  for each row execute function public.check_employee_catalog();
create trigger employees_guard_insert before insert on public.employees
  for each row execute function public.guard_employee_insert();

-- ---------------------------------------------------------------------------
-- Security advisor fixes: helper functions can't be called by signed-out
-- visitors, and trigger functions can't be called through the API at all.
-- Triggers still run them; Postgres only checks this when a trigger is made.
-- ---------------------------------------------------------------------------

revoke execute on function
  public.is_hr(), public.current_employee_id(), public.my_account(),
  public.link_employee_account(), public.link_existing_account(),
  public.notify_payslip_published(), public.notify_request_decision()
  from public, anon;
revoke execute on function
  public.link_employee_account(), public.link_existing_account(),
  public.notify_payslip_published(), public.notify_request_decision()
  from authenticated;
grant execute on function
  public.is_hr(), public.current_employee_id(), public.my_account()
  to authenticated;
